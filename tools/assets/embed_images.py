#!/usr/bin/env python3
"""Embeds images in the place itself, so new art shows without uploading to Roblox.

Each image becomes base64(zstd(RGBA8 pixels)) in src/shared/Assets/Embedded.luau; the client draws it
into an EditableImage (src/client/UI/EmbeddedImage.luau) and labels show it via ImageContent. Keep
images small: every embedded pixel ships in the place and sits in client memory.

Images: the map sprites (assets/map_sprites: plates, glyphs, units, ui/<key>) plus any listed in
EXTRA (name -> path under the repo, e.g. the battle pass art).

Usage: python3 tools/assets/embed_images.py
"""
import base64
import os

import zstandard
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SPRITES = os.path.join(ROOT, "assets", "map_sprites")
OUT = os.path.join(ROOT, "src", "shared", "Assets", "Embedded.luau")

MAP_SPRITES = ["plates", "plates_one", "glyphs", "units", "units_one"]
UI_KEYS = ["city", "port", "factory", "defense", "sam", "silo", "artillery", "airfield", "railgun",
           "warship", "atom", "hydrogen", "mirv", "boat"]
EXTRA_DIR = os.path.join(ROOT, "assets", "embedded")  # every PNG here is embedded under its file name


def entries():
    for n in MAP_SPRITES:
        yield "sprites/" + n, os.path.join(SPRITES, n + ".png")
    for k in UI_KEYS:
        yield "ui/" + k, os.path.join(SPRITES, "ui", k + ".png")
    # the map effects atlas (explosions, conquest flags, laser turret flashes, fire, smoke)
    yield "fx/map_fx", os.path.join(ROOT, "assets", "map_fx", "map_fx.png")
    if os.path.isdir(EXTRA_DIR):
        for dp, _, fn in sorted(os.walk(EXTRA_DIR)):
            for f in sorted(fn):
                if f.endswith(".png"):
                    rel = os.path.relpath(os.path.join(dp, f), EXTRA_DIR)[:-4].replace(os.sep, "/")
                    yield rel, os.path.join(dp, f)


def main():
    z = zstandard.ZstdCompressor(level=19, write_content_size=True)
    lines = [
        "-- GENERATED by tools/assets/embed_images.py — do not edit by hand.",
        "-- Images shipped inside the place: name -> { w, h, data = base64(zstd(RGBA8 pixels)) }.",
        "-- Drawn at runtime by src/client/UI/EmbeddedImage.luau (EditableImage), no upload needed.",
        "return {",
    ]
    total = 0
    for name, path in entries():
        im = Image.open(path).convert("RGBA")
        w, h = im.size
        blob = base64.b64encode(z.compress(im.tobytes())).decode("ascii")
        total += len(blob)
        lines.append('\t["%s"] = { w = %d, h = %d, data = "%s" },' % (name, w, h, blob))
    lines += ["}", ""]
    open(OUT, "w", encoding="utf-8").write("\n".join(lines))
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(lines) - 5} images, {total // 1024} KB")


if __name__ == "__main__":
    main()

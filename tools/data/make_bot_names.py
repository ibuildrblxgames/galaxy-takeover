#!/usr/bin/env python3
"""Galaxy Takeover bot names (the small random players): half alien species, half space crews.
Writes src/shared/Data/Tribes.luau ({ names = {...} }, the shape WorldMap.tribe_names reads).

Usage: python3 tools/data/make_bot_names.py [--count 480] [--seed 5]
"""
import argparse
import os
import random

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "src", "shared", "Data", "Tribes.luau")

# alien species: an alien-sounding name + a word for a group of creatures
ALIEN_START = ["Gl", "Vex", "Zub", "Kr", "Ml", "Qu", "Pl", "Yr", "Th", "Xy", "Sk", "Br", "Nub", "Fl",
               "Gr", "Zz", "Oo", "Bl", "Sn", "Dr", "Kw", "Tw", "Vr", "Ix", "Ug", "Ch", "Mor", "Sl"]
ALIEN_MID = ["o", "a", "ee", "i", "u", "oo", "y", "ax", "ib", "orr", "ul", "ix", "ae", "on"]
ALIEN_END = ["rp", "xi", "b", "x", "g", "zz", "th", "ck", "m", "rk", "sh", "p", "n", "lk", "gg", "t", "x", "'k"]
ALIEN_END_SOFT = ["", "a", "o", "i", "ek", "us", "is", "ar", "on", "ul"]  # after a mid that ends hard
GROUPS = ["Spawn", "Brood", "Swarm", "Hive", "Kin", "Clutch", "Pod", "Throng", "Bloom", "Coil",
          "Nest", "Shoal", "Drift", "Horde", "Host", "Choir", "Legion", "Colony"]
# never inside an alien word (rude words, and text Roblox filters)
BLOCK = ["slut", "shit", "cum", "fag", "nig", "tit", "cock", "dick", "dic", "puss", "ass", "anal", "rap",
         "fuk", "fuck", "sex", "porn", "nazi", "piss", "crap", "damn", "bitch", "whor", "hoe", "gay", "jew",
         "coon", "spic", "poo", "pee", "butt", "boob", "cunt", "twat", "wank", "nut", "kys", "kill", "die",
         "weed", "bong", "fck", "hell", "god", "sus", "nob", "tard", "homo", "lsd", "thc", "pot", "kkk"]
# space crews: a gritty adjective-ish first word + a crew word
CREW_A = ["Rust", "Void", "Star", "Comet", "Nova", "Iron", "Salvage", "Neon", "Ion", "Dust", "Grav",
          "Plasma", "Cinder", "Hex", "Orbit", "Rad", "Moon", "Solar", "Flux", "Chrome", "Static",
          "Quasar", "Meteor", "Pulsar", "Warp", "Black Sun", "Red Giant", "Dark Matter", "Zero-G",
          "Gamma", "Photon", "Rocket", "Asteroid", "Ember", "Frost", "Toxic", "Laser", "Turbo"]
CREW_MID = ["fang", "jaw", "tail", "claw", "hook", "spark", "burn", "wing", "eye", "bolt", "scar", "skull"]
CREW_B = ["Raiders", "Runners", "Jackals", "Corsairs", "Crew", "Gang", "Wreckers", "Outlaws",
          "Rovers", "Smugglers", "Reavers", "Haulers", "Pirates", "Marauders", "Drifters", "Scavengers",
          "Brigade", "Syndicate", "Riders", "Hounds"]


def alien(rng):
    while True:
        mid = rng.choice(ALIEN_MID)
        end = rng.choice(ALIEN_END if mid[-1] in "aeiouy" else ALIEN_END_SOFT)
        word = rng.choice(ALIEN_START) + mid + end
        if not any(b in word.lower() for b in BLOCK) and len(word) >= 4:
            return word.capitalize() + " " + rng.choice(GROUPS)


def crew(rng):
    a = rng.choice(CREW_A)
    if " " not in a and rng.random() < 0.4:
        return a + rng.choice(CREW_MID) + " " + rng.choice(CREW_B)
    return a + " " + rng.choice(CREW_B)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--count", type=int, default=480)
    ap.add_argument("--seed", type=int, default=5)
    a = ap.parse_args()
    rng = random.Random(a.seed)
    names, seen = [], set()
    while len(names) < a.count:
        n = alien(rng) if len(names) % 2 == 0 else crew(rng)
        if n.lower() not in seen and len(n) <= 22:
            seen.add(n.lower())
            names.append(n)
    lines = ["-- GENERATED by tools/data/make_bot_names.py. Do not edit.",
             "-- Bot names (the small random players): half alien species, half space crews.",
             "return {", "\tnames = {"]
    lines += ['\t\t"%s",' % n for n in names]
    lines += ["\t},", "}", ""]
    open(OUT, "w", encoding="utf-8").write("\n".join(lines))
    print(len(names), "names, e.g.", ", ".join(names[:12]))


if __name__ == "__main__":
    main()
